const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {createDemo}=require('../lib/demo/seed.ts');
const {applyCommand}=require('../lib/demo/commands.ts');
const {workEmail,beginVerification,verifyEmail,createOrganisation,acceptDepartmentInvitation,accountForEmail}=require('../lib/demo/organisation.ts');
const profile={name:'Greenfield Hospital',adminName:'Ada Green',type:'Hospital',phone:'+2348012345678',address:'1 Demo Road',city:'Lagos',state:'Lagos',country:'Nigeria',website:'https://greenfield.example'};
assert.throws(()=>workEmail('owner@gmail.com'),/official work email/);
assert.throws(()=>workEmail('invalid-address'),/valid official/);
assert.equal(workEmail(' Owner@Greenfield.example '),'owner@greenfield.example');
let demo=createDemo(),pending=beginVerification(demo,'owner@greenfield.example');
assert.throws(()=>createOrganisation(demo,pending,profile),/Verify/);
assert.throws(()=>verifyEmail(pending,'wrong-token'),/invalid/);
assert.throws(()=>verifyEmail({...pending,expiresAt:'2020-01-01T00:00:00Z'},pending.token),/expired/);
pending=verifyEmail(pending,pending.token);
const created=createOrganisation(demo,pending,profile);demo=created.demo;
const orgId=created.session.organisationId;
assert.equal(created.session.role,'admin');
assert.equal(demo.datasets[orgId].staff.length,1);
assert.equal(demo.datasets[orgId].staff[0].owner,true);
assert.equal(demo.datasets[orgId].patients.length,0);
assert.equal(demo.datasets[orgId].staff[0].department,'Administration');
assert.equal(accountForEmail(demo,'owner@greenfield.example').role,'admin');
assert.throws(()=>createOrganisation(demo,pending,profile),/already has an administrator/);
assert.throws(()=>beginVerification(demo,'stranger@greenfield.example'),/administrator to invite/);
const run=(role,type,id,values)=>demo=applyCommand(demo,orgId,role,{type,id,values});
assert.throws(()=>run('doctor','department',undefined,{name:'Cardiology'}),/cannot perform/);
run('admin','department',undefined,{name:'Cardiology',description:'Heart care team'});
assert.throws(()=>run('admin','department',undefined,{name:'cardiology'}),/already exists/);
assert.throws(()=>run('admin','inviteUser',undefined,{department:'Cardiology',name:'Dr. Zainab',email:'zainab@greenfield.example',role:''}),/Select a hospital role/);
assert.throws(()=>run('admin','inviteUser',undefined,{department:'Cardiology',name:'Dr. Zainab',email:'zainab@greenfield.example',role:'platform'}),/Select a hospital role/);
run('admin','inviteUser',undefined,{department:'Cardiology',name:'Dr. Zainab',email:'zainab@greenfield.example',role:'doctor'});
let invite=demo.datasets[orgId].invitations[0];
assert.equal(demo.datasets[orgId].staff[1].enabled,false);
assert.equal(demo.datasets[orgId].staff[1].role,'doctor');
assert.throws(()=>beginVerification(demo,'zainab@greenfield.example'),/invitation is waiting/);
assert.throws(()=>run('admin','inviteUser',undefined,{department:'Pharmacy',name:'Duplicate',email:'zainab@greenfield.example',role:'pharmacy'}),/already belongs/);
const firstToken=invite.token;
run('admin','invitationStatus',invite.id,{status:'resend'});invite=demo.datasets[orgId].invitations[0];
assert.notEqual(invite.token,firstToken);
assert.throws(()=>acceptDepartmentInvitation(demo,firstToken),/invalid or has been replaced/);
const joined=acceptDepartmentInvitation(demo,invite.token);demo=joined.demo;
assert.equal(joined.session.role,'doctor');
assert.equal(joined.session.organisationId,orgId);
assert.equal(demo.datasets[orgId].staff.filter(s=>s.owner).length,1);
assert.equal(demo.datasets[orgId].staff[1].enabled,true);
assert.equal(beginVerification(demo,'zainab@greenfield.example').kind,'existing');
assert.throws(()=>acceptDepartmentInvitation(demo,invite.token),/already been used/);
run('admin','inviteUser',undefined,{department:'Pharmacy',name:'Pharmacist Demo',email:'pharmacy@greenfield.example',role:'pharmacy'});
invite=demo.datasets[orgId].invitations[1];run('admin','invitationStatus',invite.id,{status:'revoked'});
assert.throws(()=>acceptDepartmentInvitation(demo,invite.token),/revoked/);
assert.throws(()=>run('admin','staff',demo.datasets[orgId].staff[0].id,{}),/owner cannot be disabled/);
assert.equal(demo.datasets.central.staff.length,2);
console.log('PASS: official email, verification guards, first-admin ownership, clean organisation, departments, required roles, invitations, resend/revoke/replay and organisation scope.');
